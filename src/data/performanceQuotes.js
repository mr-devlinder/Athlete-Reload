const surfaceOffsets = { home: 0, checkIn: 17, checkout: 39 }

export function getPerformanceQuote(surface, date = new Date()) {
  const pool = performanceQuotePools[surface]
  if (!pool) return ''

  const dateParts = typeof date === 'string'
    ? date.slice(0, 10).split('-').map(Number)
    : [date.getFullYear(), date.getMonth() + 1, date.getDate()]
  const dayNumber = Math.floor(Date.UTC(dateParts[0], dateParts[1] - 1, dateParts[2]) / 86400000)
  return pool[Math.abs(dayNumber + surfaceOffsets[surface]) % pool.length]
}
